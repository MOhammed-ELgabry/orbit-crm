    ADD COLUMN "countryCode" VARCHAR(2),
    ADD COLUMN "baseCurrencyCode" VARCHAR(3),
    ADD COLUMN "timezone" VARCHAR(64),
    ADD COLUMN "defaultLocale" VARCHAR(16),
    ADD COLUMN "regionalStatus" VARCHAR(16),
    ADD COLUMN "suggestedCountryCode" VARCHAR(2),
    ADD COLUMN "suggestedTimezone" VARCHAR(64),
    ADD COLUMN "suggestedLocale" VARCHAR(16),
    ADD COLUMN "regionalSource" VARCHAR(16),
    ADD COLUMN "regionalConfidence" VARCHAR(16),
    ADD COLUMN "regionalDetectedAt" TIMESTAMP(3),
    ADD COLUMN "regionalConfirmedAt" TIMESTAMP(3);

ALTER TABLE "Company" ADD CONSTRAINT "Company_regionalStatus_check"
    CHECK ("regionalStatus" IS NULL OR "regionalStatus" IN ('DETECTED', 'CONFIRMED', 'NEEDS_REVIEW'));
ALTER TABLE "Company" ADD CONSTRAINT "Company_regionalSource_check"
    CHECK ("regionalSource" IS NULL OR "regionalSource" IN ('GEOLOCATION', 'IP', 'TIMEZONE', 'LOCALE'));
ALTER TABLE "Company" ADD CONSTRAINT "Company_regionalConfidence_check"
    CHECK ("regionalConfidence" IS NULL OR "regionalConfidence" IN ('HIGH', 'MEDIUM', 'LOW', 'AMBIGUOUS'));
-- A CONFIRMED company has, by definition, an Owner-chosen country and a confirmation time.
ALTER TABLE "Company" ADD CONSTRAINT "Company_regionalConfirmed_check"
    CHECK ("regionalStatus" IS DISTINCT FROM 'CONFIRMED' OR ("countryCode" IS NOT NULL AND "regionalConfirmedAt" IS NOT NULL));

ALTER TABLE "Company" ADD CONSTRAINT "Company_countryCode_fkey"
    FOREIGN KEY ("countryCode") REFERENCES "Country"("code") ON DELETE SET NULL ON UPDATE CASCADE;
ALTER TABLE "Company" ADD CONSTRAINT "Company_suggestedCountryCode_fkey"
    FOREIGN KEY ("suggestedCountryCode") REFERENCES "Country"("code") ON DELETE SET NULL ON UPDATE CASCADE;
ALTER TABLE "Company" ADD CONSTRAINT "Company_baseCurrencyCode_fkey"
    FOREIGN KEY ("baseCurrencyCode") REFERENCES "Currency"("code") ON DELETE SET NULL ON UPDATE CASCADE;


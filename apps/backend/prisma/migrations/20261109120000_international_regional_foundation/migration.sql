-- International Foundation: regional reference data + company/user regional columns
-- + wider money scale. Additive only: no existing column is dropped or rewritten
-- except Deal.amount, which is WIDENED (Decimal(12,2) -> Decimal(19,4)) and therefore
-- keeps every existing value exactly.

-- ─── Reference tables ────────────────────────────────────────────────────────
-- Currency: ACTIVE ISO 4217 currencies only (the current currency of >= 1 country).
CREATE TABLE "Currency" (
    "code" VARCHAR(3) NOT NULL,
    "nameEn" TEXT NOT NULL,
    "nameAr" TEXT NOT NULL,
    "symbol" VARCHAR(8) NOT NULL,
    "minorUnit" SMALLINT NOT NULL,
    "isActive" BOOLEAN NOT NULL DEFAULT true,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "Currency_pkey" PRIMARY KEY ("code"),
    CONSTRAINT "Currency_code_format_check" CHECK ("code" ~ '^[A-Z]{3}$'),
    CONSTRAINT "Currency_minorUnit_check" CHECK ("minorUnit" BETWEEN 0 AND 4)
);

CREATE TABLE "Country" (
    "code" VARCHAR(2) NOT NULL,
    "alpha3" VARCHAR(3) NOT NULL,
    "numericCode" VARCHAR(3) NOT NULL,
    "nameEn" TEXT NOT NULL,
    "nameAr" TEXT NOT NULL,
    "nativeName" TEXT NOT NULL,
    "defaultCurrencyCode" VARCHAR(3),
    "defaultLocale" VARCHAR(16),
    "defaultTimezone" VARCHAR(64),
    "isActive" BOOLEAN NOT NULL DEFAULT true,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "Country_pkey" PRIMARY KEY ("code"),
    CONSTRAINT "Country_code_format_check" CHECK ("code" ~ '^[A-Z]{2}$')
);

CREATE UNIQUE INDEX "Country_alpha3_key" ON "Country"("alpha3");
CREATE UNIQUE INDEX "Country_numericCode_key" ON "Country"("numericCode");
CREATE INDEX "Country_defaultCurrencyCode_idx" ON "Country"("defaultCurrencyCode");

ALTER TABLE "Country" ADD CONSTRAINT "Country_defaultCurrencyCode_fkey"
    FOREIGN KEY ("defaultCurrencyCode") REFERENCES "Currency"("code") ON DELETE SET NULL ON UPDATE CASCADE;

-- Single-use stash carrying optional regional hints across the OAuth redirect.
CREATE TABLE "RegionalHintHandoff" (
    "id" TEXT NOT NULL,
    "tokenHash" TEXT NOT NULL,
    "hints" JSONB NOT NULL,
    "expiresAt" TIMESTAMP(3) NOT NULL,
    "consumedAt" TIMESTAMP(3),
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "RegionalHintHandoff_pkey" PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX "RegionalHintHandoff_tokenHash_key" ON "RegionalHintHandoff"("tokenHash");
CREATE INDEX "RegionalHintHandoff_expiresAt_idx" ON "RegionalHintHandoff"("expiresAt");

